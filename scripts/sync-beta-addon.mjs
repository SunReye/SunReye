#!/usr/bin/env node
// Generate the `sunreye-beta/` addon manifest from the stable `sunreye/` one.
//
// Home Assistant's Supervisor only ever reads an addon repository's DEFAULT
// branch, so a beta addon has to exist on master — it cannot live on `dev`.
// It is a second store entry (slug `sunreye-beta`) that installs side by side
// with stable: its own /data, its own embedded postgres, so testing a beta
// never touches the production addon's database.
//
// The Supervisor pulls `<image>:<version>`, which is why a moving docker tag
// cannot drive addon updates — every beta needs its own immutable tag, and
// `version` in config.yaml must name it. docker-addon-beta.yml builds
// `beta.<YYYYMMDD>-<short sha>` on each push to `dev` and then runs this script
// on master to publish it.
//
// Everything under sunreye-beta/ is DERIVED — never hand-edit it. Only
// config.yaml is transformed (name/slug/version/arch/panel/boot); the docs,
// translations, and brand assets are byte copies. No Dockerfile or rootfs is
// needed because config.yaml sets `image:`, so the Supervisor pulls the
// prebuilt image instead of building anything locally.
//
// CHANGELOG.md is the one derived file this script does NOT own — it needs git
// history rather than a file transform, so scripts/beta-changelog.mjs writes it
// in the same publish step.
//
// Usage:
//   node scripts/sync-beta-addon.mjs --version=1.3.0-beta.7
//
// The source `sunreye/` is read from the working tree, which is how the
// workflow keeps the manifest honest: it checks out master (where the file has
// to be committed) but restores `sunreye/` from `dev` first, so the beta
// manifest describes the options schema of the image it is about to ship, not
// the last release's. Without --version the current beta version is kept.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const STABLE = join(ROOT, "sunreye");
const BETA = join(ROOT, "sunreye-beta");

const HEADER = `# GENERATED by scripts/sync-beta-addon.mjs — do not edit.
#
# Beta channel of the SunReye addon: a separate store entry (slug
# sunreye-beta) that installs alongside the stable one with its own /data and
# its own embedded postgres, so beta testing cannot corrupt production data.
# Built from the \`dev\` branch by .github/workflows/docker-addon-beta.yml.
#
# amd64 only, and \`boot: manual\` — most inverters accept a single Modbus TCP
# connection at a time, so stop the stable addon (or set inverter_simulate)
# before starting this one.
`;

// Each rule must match exactly once. A rule that stops matching means
// sunreye/config.yaml changed shape, and silently skipping it would ship a
// beta manifest that still calls itself "SunReye" or claims slug `sunreye`
// (which collides with the stable addon) — so a miss is a hard error.
const RULES = [
  { find: /^name: .*$/m, replace: () => "name: SunReye (beta)" },
  { find: /^slug: .*$/m, replace: () => "slug: sunreye-beta" },
  { find: /^panel_title: .*$/m, replace: () => "panel_title: SunReye beta" },
  // Only amd64 images are built for beta (aarch64 needs slow QEMU emulation);
  // listing an arch whose tag does not exist makes the Supervisor fail the
  // install rather than hide the addon.
  { find: /^arch:\n(?: {2}- \w+\n)+/m, replace: () => "arch:\n  - amd64\n" },
  // Stable is `boot: auto`; a beta must not come back up on its own after an
  // HA restart and start fighting the stable addon for the inverter.
  { find: /^boot: .*$/m, replace: () => "boot: manual" },
];

/** Apply one rule, failing loudly unless it matched exactly once. */
function applyRule(text, { find, replace }) {
  const hits = text.match(new RegExp(find.source, find.flags.replace("m", "gm")))?.length ?? 0;
  if (hits !== 1) {
    throw new Error(
      `sync-beta-addon: rule ${find} matched ${hits}× in sunreye/config.yaml (expected ` +
        `exactly 1) — the stable manifest changed shape, update RULES.`,
    );
  }
  return text.replace(find, replace());
}

/** Derive the beta config.yaml text from the stable one. */
function renderConfig(stableText, version) {
  // Drop the stable file's leading comment block; HEADER replaces it.
  let out = stableText.replace(/^(?:#[^\n]*\n)+/, HEADER);
  for (const rule of RULES) out = applyRule(out, rule);
  return applyRule(out, { find: /^version: .*$/m, replace: () => `version: ${version}` });
}

/** The version already published to the beta channel, or a seed for the first run. */
function currentBetaVersion() {
  const path = join(BETA, "config.yaml");
  if (!existsSync(path)) return null;
  return (
    readFileSync(path, "utf8")
      .match(/^version: (.+)$/m)?.[1]
      .trim() ?? null
  );
}

const requested = process.argv
  .slice(2)
  .find((a) => a.startsWith("--version="))
  ?.slice("--version=".length);

const version = requested ?? currentBetaVersion();
if (!version) {
  console.error(
    "sync-beta-addon: no existing sunreye-beta/config.yaml — pass --version=<x.y.z-beta.n>",
  );
  process.exit(1);
}

// path → contents. Text files are generated or copied; assets are byte copies.
const files = new Map([
  ["config.yaml", renderConfig(readFileSync(join(STABLE, "config.yaml"), "utf8"), version)],
  ["DOCS.md", readFileSync(join(STABLE, "DOCS.md"))],
  ["translations/en.yaml", readFileSync(join(STABLE, "translations/en.yaml"))],
  ["icon.png", readFileSync(join(STABLE, "icon.png"))],
  ["logo.png", readFileSync(join(STABLE, "logo.png"))],
  [
    "README.md",
    `# SunReye (beta)

Pre-release builds of the [SunReye addon](../sunreye/README.md), built from the
\`dev\` branch. Installs alongside the stable addon with a separate database, so
you can try unreleased changes without touching production data.

**Not for production.** Migrations here may still change before release, and
downgrading back to the stable addon is not supported — take a Home Assistant
backup first.

Most inverters accept only one Modbus TCP connection at a time, so stop the
stable addon before starting this one, or run it with \`inverter_simulate\`.
`,
  ],
]);

for (const [rel, contents] of files) {
  const path = join(BETA, rel);
  mkdirSync(join(path, ".."), { recursive: true });
  writeFileSync(path, Buffer.isBuffer(contents) ? contents : Buffer.from(contents, "utf8"));
}

console.log(`sunreye-beta/ synced at version ${version}`);
