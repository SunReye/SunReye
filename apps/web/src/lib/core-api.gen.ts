        ApiKeyView: {
            createdAt: string;
            /** Format: int64 */
            id: number;
            name: string;
            /** @description The key's first characters. */
            start: string;
            userEmail: string;
            /** Format: int64 */
            userId: number;
            userName: string;
        };
        /** @description The SPA areas this core serves; the SPA hides every area that reads false. */
        Capabilities: {
            automations: boolean;
            controls: boolean;
            history: boolean;
            profileSources: boolean;
            restart: boolean;
            statistics: boolean;
        };
